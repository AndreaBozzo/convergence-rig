def ensure_polaris_namespace(
    polaris_cfg: PolarisConfig,
    token: str,
    *,
    catalog_name: str,
    namespace: str,
) -> dict[str, Any]:
    """Ensure a top-level Iceberg namespace exists in Polaris via Iceberg REST."""
    hdrs = _auth_headers(token, polaris_cfg.realm)
    wh_q = urllib.parse.urlencode({"warehouse": catalog_name})
    c_status, c_body, c_raw = http_json_raw(
        f"{polaris_cfg.host_catalog_url}/v1/config?{wh_q}",
        headers=hdrs,
    )
    if c_status != 200 or not isinstance(c_body, dict):
        raise RuntimeError(f"Polaris /v1/config failed: {c_status} {c_raw!r}")
    prefix = (c_body.get("overrides") or {}).get("prefix") or (
        c_body.get("defaults") or {}
    ).get("prefix") or catalog_name

    ns_url = f"{polaris_cfg.host_catalog_url}/v1/{urllib.parse.quote(str(prefix), safe='')}/namespaces"
    status, body, raw = http_json_raw(
        ns_url,
        method="POST",
        headers=hdrs,
        body={"namespace": [namespace]},
    )
    if status in (200, 201):
        return {"action": "created", "http_status": status, "prefix": prefix, "body": body}
    if status == 409:
        return {"action": "already_exists", "http_status": status, "prefix": prefix}
    raise RuntimeError(f"Failed to create Polaris namespace {namespace!r}: {status} {raw!r}")


def rest_load_table_polaris(
    polaris_cfg: PolarisConfig,
    *,
    catalog_name: str,
    namespace: str,
    table: str,
    access_token: str,
    request_vended_credentials: bool = True,
) -> dict[str, Any]:
    """Call Polaris /v1/config then Iceberg REST LoadTable as an authenticated principal."""
    auth_hdrs = _auth_headers(access_token, polaris_cfg.realm)
    wh_q = urllib.parse.urlencode({"warehouse": catalog_name})
    cfg_url = f"{polaris_cfg.host_catalog_url}/v1/config?{wh_q}"
    cfg_status, cfg_body, cfg_raw = http_json_raw(cfg_url, headers=auth_hdrs)
    if cfg_status != 200 or not isinstance(cfg_body, dict):
        return {
            "stage": "catalog_config",
            "url": cfg_url,
            "http_status": cfg_status,
            "allowed": False,
            "body": cfg_body,
            "raw_body": cfg_raw,
        }

    prefix = (cfg_body.get("overrides") or {}).get("prefix") or (
        cfg_body.get("defaults") or {}
    ).get("prefix") or catalog_name
    table_url = (
        f"{polaris_cfg.host_catalog_url}/v1/{urllib.parse.quote(str(prefix), safe='')}"
        f"/namespaces/{urllib.parse.quote(namespace, safe='')}"
        f"/tables/{urllib.parse.quote(table, safe='')}"
    )
    tbl_headers = dict(auth_hdrs)
    if request_vended_credentials:
        tbl_headers["X-Iceberg-Access-Delegation"] = "vended-credentials"
    tbl_status, tbl_body, tbl_raw = http_json_raw(table_url, headers=tbl_headers)
    return {
        "stage": "load_table",
        "catalog_config": cfg_body,
        "url": table_url,
        "prefix": prefix,
        "http_status": tbl_status,
        "allowed": tbl_status == 200,
        "body": tbl_body,
        "raw_body": tbl_raw if tbl_status != 200 else None,
    }


def fetch_polaris_table_metadata(
    polaris_cfg: PolarisConfig,
    *,
    catalog_name: str,
    namespace: str = "public",
    table: str = "orders",
    client_id: str | None = None,
    client_secret: str | None = None,
    scope: str = "PRINCIPAL_ROLE:ALL",
    request_vended_credentials: bool = True,
    allow_not_found: bool = False,
) -> dict[str, Any] | None:
    """Fetch redacted Iceberg LoadTable metadata from Polaris in the same shape as lab.reader."""
    token, _ = fetch_polaris_token(
        polaris_cfg.host_token_url,
        client_id or polaris_cfg.root_client_id,
        client_secret or polaris_cfg.root_client_secret,
        scope=scope,
        realm=polaris_cfg.realm,
    )
    res = rest_load_table_polaris(
        polaris_cfg,
        catalog_name=catalog_name,
        namespace=namespace,
        table=table,
        access_token=token,
        request_vended_credentials=request_vended_credentials,
    )
    if not res["allowed"]:
        if allow_not_found and res["http_status"] == 404:
            return None
        raise RuntimeError(
            f"Polaris LoadTable failed for {catalog_name}.{namespace}.{table}: "
            f"status={res['http_status']} body={res.get('raw_body') or res.get('body')!r}"
        )
    payload = res["body"]
    redacted = redact_load_table_response(payload)
    return {
        "catalog_config": res.get("catalog_config"),
        "table_url": res["url"],
        "metadata_location": payload.get("metadata-location"),
        "config": redacted["config"],
        "storage_credentials": redacted["storage_credentials"],
        "metadata": payload.get("metadata"),
    }


