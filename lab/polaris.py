def load_polaris_config(
    env_file: Path | None = None,
    overrides: dict[str, str] | None = None,
) -> PolarisConfig:
    primary = env_file or DEFAULT_ENV_FILE
    merged = parse_env_file(primary)
    if env_file is None and LOCAL_ENV_FILE.exists():
        merged.update(parse_env_file(LOCAL_ENV_FILE))
    for key in list(merged.keys()):
        if key in os.environ:
            merged[key] = os.environ[key]
    if overrides:
        merged.update(overrides)
    return PolarisConfig(
        polaris_port=int(merged.get("POLARIS_PORT", "18183")),
        polaris_mgmt_port=int(merged.get("POLARIS_MGMT_PORT", "18184")),
        pg2iceberg_polaris_metrics_port=int(
            merged.get("PG2ICEBERG_POLARIS_METRICS_PORT", "19091")
        ),
        realm=merged.get("POLARIS_REALM", "POLARIS"),
        root_client_id=merged.get("POLARIS_ROOT_CLIENT_ID", "root"),
        root_client_secret=merged.get("POLARIS_ROOT_CLIENT_SECRET", "cdclab_polaris_root_secret"),
        catalog_name=merged.get("POLARIS_CATALOG", "cdclab_polaris"),
        authz_catalog_name=merged.get("POLARIS_AUTHZ_CATALOG", "cdclab_polaris_authz"),
    )


def http_json_raw(
    url: str,
    *,
    method: str = "GET",
    body: dict[str, Any] | None = None,
    headers: dict[str, str] | None = None,
    timeout: float = 20.0,
) -> tuple[int, Any, str]:
    data = json.dumps(body).encode("utf-8") if body is not None else None
    req_headers = {"Accept": "application/json"}
    if data is not None:
        req_headers["Content-Type"] = "application/json"
    if headers:
        req_headers.update(headers)
    req = urllib.request.Request(url, data=data, headers=req_headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            raw = resp.read().decode("utf-8")
            return resp.status, (json.loads(raw) if raw.strip() else None), raw
    except urllib.error.HTTPError as exc:
        raw = exc.read().decode("utf-8", errors="replace")
        try:
            parsed: Any = json.loads(raw) if raw.strip() else None
        except json.JSONDecodeError:
            parsed = raw
        return exc.code, parsed, raw


def fetch_polaris_token(
    token_url: str,
    client_id: str,
    client_secret: str,
    *,
    scope: str = "PRINCIPAL_ROLE:ALL",
    realm: str | None = None,
    timeout: float = 15.0,
) -> tuple[str, dict[str, Any]]:
    """Request an OAuth2 client_credentials Bearer token from Polaris."""
    form = urllib.parse.urlencode(
        {
            "grant_type": "client_credentials",
            "client_id": client_id,
            "client_secret": client_secret,
            "scope": scope,
        }
    ).encode("utf-8")
    headers = {"Content-Type": "application/x-www-form-urlencoded"}
    if realm:
        headers["Polaris-Realm"] = realm
    req = urllib.request.Request(token_url, data=form, headers=headers, method="POST")
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        payload = json.loads(resp.read().decode("utf-8"))
    token = payload["access_token"]
    claims: dict[str, Any] = {}
    if len(token.split(".")) == 3:
        try:
            claims = decode_jwt_payload(token)
        except Exception:
            claims = {}
    return token, {
        "token_type": payload.get("token_type"),
        "expires_in": payload.get("expires_in"),
        "scope": payload.get("scope"),
        "claims": claims,
    }


def _auth_headers(token: str, realm: str | None = None) -> dict[str, str]:
    hdrs = {"Authorization": f"Bearer {token}"}
    if realm:
        hdrs["Polaris-Realm"] = realm
    return hdrs


def create_s3_catalog(
    polaris_cfg: PolarisConfig,
    lab_cfg: LabConfig,
    token: str,
    *,
    catalog_name: str,
    key_prefix: str,
    sts_unavailable: bool = False,
    kms_unavailable: bool = True,
    role_arn: str = SYNTHETIC_SILO_ROLE_ARN,
) -> dict[str, Any]:
    """Create an INTERNAL Polaris S3 catalog backed by Silo, idempotently."""
    mgmt = polaris_cfg.host_management_url
    hdrs = _auth_headers(token, polaris_cfg.realm)
    get_url = f"{mgmt}/catalogs/{urllib.parse.quote(catalog_name, safe='')}"
    g_status, g_body, _ = http_json_raw(get_url, headers=hdrs)
    if g_status == 200 and isinstance(g_body, dict):
        return {"action": "already_exists", "http_status": g_status, "catalog": g_body}

    base_location = f"s3://{lab_cfg.silo_bucket}/{key_prefix.strip('/')}"
    storage_cfg: dict[str, Any] = {
        "storageType": "S3",
        "allowedLocations": [base_location],
        "endpoint": lab_cfg.silo_advertised_endpoint,
        "region": lab_cfg.silo_region,
        "pathStyleAccess": True,
        "stsUnavailable": sts_unavailable,
        "kmsUnavailable": kms_unavailable,
    }
    if not sts_unavailable:
        storage_cfg["roleArn"] = role_arn
        storage_cfg["stsEndpoint"] = lab_cfg.silo_advertised_endpoint

    payload = {
        "catalog": {
            "name": catalog_name,
            "type": "INTERNAL",
            "properties": {
                "default-base-location": base_location,
            },
            "storageConfigInfo": storage_cfg,
        }
    }
    c_status, c_body, c_raw = http_json_raw(
        f"{mgmt}/catalogs",
        method="POST",
        headers=hdrs,
        body=payload,
    )
    if c_status not in (200, 201):
        raise RuntimeError(
            f"Polaris create catalog {catalog_name!r} failed: status={c_status} body={c_raw!r}"
        )
    g2_status, g2_body, _ = http_json_raw(get_url, headers=hdrs)
    return {
        "action": "created",
        "http_status": c_status,
        "request_payload": payload,
        "catalog": g2_body if g2_status == 200 else c_body,
    }


def create_principal(
    polaris_cfg: PolarisConfig,
    token: str,
    *,
    name: str,
) -> dict[str, Any]:
    """Create a Polaris principal and return its entity metadata plus generated client credentials."""
    status, body, raw = http_json_raw(
        f"{polaris_cfg.host_management_url}/principals",
        method="POST",
        headers=_auth_headers(token, polaris_cfg.realm),
        body={"principal": {"name": name, "properties": {"purpose": "cdclab-p1"}}},
    )
    if status not in (200, 201) or not isinstance(body, dict):
        raise RuntimeError(f"Failed to create Polaris principal {name!r}: {status} {raw!r}")
    return body


